import numpy as np

a = np.zeros((3, 4))
idx = np.array([[0], [2], [1]])
np.put_along_axis(a, idx, 5.0, axis=1)
print(a)
b = np.arange(6).reshape(2, 3)
np.put_along_axis(b, np.array([[2], [0]]), np.array([[10], [20]]), axis=1)
print(b)
print(np.add.reduce(np.arange(5)), np.multiply.accumulate(np.arange(1, 6)))
print(np.maximum.reduce(np.array([[1, 5], [7, 2]]), axis=0))
print(np.add.outer(np.arange(3), np.arange(2)))
c = np.zeros(5)
np.add.at(c, [0, 0, 3], 1.0)
print(c)
print(np.logaddexp(1.0, 2.0).round(6))
print(np.pad(np.ones((2, 2)), 1))
print(np.pad(np.arange(4), (1, 2), mode='constant', constant_values=9))
print(type(np.add).__name__)
