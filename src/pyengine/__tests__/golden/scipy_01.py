import numpy as np
from scipy import stats, special
from scipy.spatial import distance

print(round(stats.norm.pdf(0.5), 12), stats.norm.cdf([-1.96, 0, 1.0]).round(6), stats.norm.ppf([0.025, 0.5, 0.975, 0.999]).round(6))
print(stats.norm(loc=2, scale=3).pdf(2.0), stats.norm(2, 3).cdf(5.0), round(stats.norm(2, 3).ppf(0.9), 10))
print(round(stats.norm.sf(1.5), 12), stats.norm.mean(), stats.norm(1, 2).var(), stats.norm(1, 2).std(), [round(float(v), 6) for v in stats.norm.interval(0.95)])
rs = np.random.RandomState(0)
print(stats.norm.rvs(size=4, random_state=rs), stats.uniform(2, 3).rvs(random_state=rs), stats.randint(1, 10).rvs(size=5, random_state=rs))
print(stats.expon(scale=2).rvs(size=3, random_state=rs).round(9), round(stats.loguniform(1e-3, 1e2).rvs(random_state=rs), 9), stats.loguniform(0.1, 10).rvs(size=3, random_state=rs).round(9))
print(stats.poisson.rvs(3, size=5, random_state=rs), stats.binom.rvs(10, 0.3, size=4, random_state=rs), stats.bernoulli(0.5).rvs(size=6, random_state=rs))
print(stats.poisson.pmf([0, 1, 2, 3], 2.0).round(6), round(stats.poisson.cdf(2, 2.0), 10), stats.binom.pmf([0, 3, 10], 10, 0.3).round(6), round(stats.binom.cdf(3, 10, 0.3), 10))
print(stats.uniform.pdf(0.5), stats.uniform(1, 2).cdf(2.0), stats.expon.cdf(1.0), stats.expon.ppf(0.5), stats.randint(0, 5).pmf(3), stats.randint(0, 5).cdf(2))
print(round(stats.t.cdf(2.0, 5), 9), round(stats.t.sf(2.5, 10), 9), round(stats.t.ppf(0.975, 10), 9), round(stats.t(8).pdf(0.3), 9))
a = np.array([2.0, 4.0, 4.0, 4.0, 5.0, 5.0, 7.0, 9.0])
b = np.array([1.0, 3.5, 4.5, 3.8, 6.0, 4.0, 8.0, 7.5])
print(stats.zscore(a).round(4), stats.rankdata([3, 1, 4, 1, 5, 9, 2, 6]), stats.rankdata([3, 1, 1, 2], method="min"))
r = stats.pearsonr(a, b)
print(round(r[0], 6), round(r[1], 6), round(r.statistic, 6))
sr = stats.spearmanr(a, b)
print(round(sr[0], 6), round(sr[1], 6))
print(stats.entropy([0.5, 0.25, 0.25]), stats.entropy([0.5, 0.5], base=2), round(stats.entropy([0.7, 0.3], [0.5, 0.5]), 12))
print(stats.sem(a), stats.skew(a), stats.kurtosis(a), stats.mode([1, 2, 2, 3, 3, 3, 4])[0])
t1 = stats.ttest_1samp(a, 4.0)
t2 = stats.ttest_ind(a, b)
print(round(t1[0], 6), round(t1[1], 6), round(t2[0], 6), round(t2[1], 6), round(stats.ttest_ind(a, b, equal_var=False)[1], 6))
print(special.expit([-2.0, 0.0, 3.0]).round(6), special.logit(0.8), special.erf([0.5, 1.0]).round(6), round(special.logsumexp([1.0, 2.0, 3.0]), 12))
print(special.softmax([1.0, 2.0, 3.0]).round(6), special.softmax([[1.0, 2.0], [3.0, 5.0]], axis=1).round(4), special.log_softmax([1.0, 2.0, 3.0]).round(6))
print(special.comb(10, 3), special.comb(10, 3, exact=True), round(special.gammaln(5.0), 12), special.xlogy(0, 0.0), round(special.betainc(2.0, 3.0, 0.4), 12))
u = np.array([1.0, 2.0, 3.0])
v = np.array([2.0, 0.0, 4.0])
print(distance.euclidean(u, v), distance.cityblock(u, v), distance.cosine(u, v), distance.chebyshev(u, v), distance.minkowski(u, v, 3), round(distance.correlation(u, v), 12))
A = np.array([[0.0, 0.0], [1.0, 1.0], [2.0, 0.0]])
B = np.array([[1.0, 0.0], [0.0, 2.0]])
print(distance.cdist(A, B).round(4), distance.cdist(A, B, "cosine").round(4)[1:], distance.cdist(A, B, "cityblock"))
print(distance.pdist(A).round(4), distance.squareform(distance.pdist(A)).round(3))
