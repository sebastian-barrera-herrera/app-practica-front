export function unicodeByName(name: string): number | null {
  const v = UNI_NAMES[name.toUpperCase()];
  return v === undefined ? null : v;
}

const REVERSE = new Map<number, string>();
for (const [k, v] of Object.entries(UNI_NAMES)) if (!REVERSE.has(v)) REVERSE.set(v, k);

/** nombre oficial de un punto de código (null si no está en la tabla) */
export function unicodeName(cp: number): string | null {
  return REVERSE.get(cp) ?? null;
}
